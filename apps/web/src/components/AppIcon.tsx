export type IconName = keyof typeof ICONS;

export function AppIcon({
  name,
  size = 18,
  strokeWidth = 1.8,
  className,
  ...props
}: { name: IconName } & Omit<LucideProps, 'ref'>) {
  const Component = ICONS[name];
  return <Component aria-hidden="true" focusable="false" size={size} strokeWidth={strokeWidth} className={className} {...props} />;
}
