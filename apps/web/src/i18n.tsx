export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem('mc.locale');
    return stored === 'en' ? 'en' : 'fr';
  });

  useEffect(() => {
    localStorage.setItem('mc.locale', locale);
    document.documentElement.lang = locale;
    document.title = locale === 'fr' ? 'Mauritius Compta' : 'Mauritius Compta';
  }, [locale]);

  const setLocale = useCallback((l: Locale) => setLocaleState(l), []);
  const t = useCallback(
    (key: string) => dictionaries[locale][key] ?? dictionaries.fr[key] ?? key,
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

export function translateError(code: string | undefined, message: string | undefined, t: (k: string) => string): string {
  if (code) {
    const key = `error.${code}`;
    const translated = t(key);
    if (translated !== key) return translated;
  }
  return message ?? t('common.error');
}
