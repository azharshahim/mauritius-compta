const dictionaries: Record<Locale, Dict> = { fr, en };

export function t(locale: Locale | undefined | null, key: string): string {
  const lang: Locale = locale === 'en' ? 'en' : 'fr';
  return dictionaries[lang][key] ?? dictionaries.fr[key] ?? key;
}

/** Resolves a locale from an Accept-Language header or explicit value. */
export function resolveLocale(input?: string | null): Locale {
  if (!input) return 'fr';
  const lower = input.toLowerCase();
  if (lower.startsWith('en')) return 'en';
  if (lower.startsWith('fr')) return 'fr';
  return 'fr';
}
